n = int(input('Введіть ціле число: '))

if n > 0:
    print('Число додатне')
elif n < 0:
    print('Число від\'ємне')
else:
    print('Число нульове')

parity = 'парне' if n % 2 == 0 else 'непарне'
print(f'Число {parity}')

if n % 3 == 0 and n % 5 == 0:
    print('Число ділиться одночасно на 3 і на 5')
else:
    print('Число не ділиться одночасно на 3 і на 5')