# Створення чотирьох змінних (цілі та дробові числа) через input()
a = int(input("Введіть перше число (ціле): "))
b = float(input("Введіть друге число (дробове): "))
c = int(input("Введіть третє число (ціле): "))
d = float(input("Введіть четверте число (дробове): "))

# Виконання арифметичних дій над числами, результати записуються у список
# round(значення, 2) — округлення до двох знаків після коми
addition = round(a + b, 2)
subtraction = round(c - d, 2)
multiplication = round(a * d, 2)
division = round(b / d, 2)
power = round(a ** c, 2)
floor_division = a // c
modulus = a % c

results = [addition, subtraction, multiplication, division,
           power, floor_division, modulus]

print("\nСписок результатів обчислень:")
print(results)

# Визначити кількість елементів списку
count = len(results)
print(f"\nКількість елементів у списку: {count}")

# Вивести парні елементи попереднього списку
even_by_position = results[1::2]
print("Елементи на парних позиціях:", even_by_position)

# Обмін місцями 2-го та 5-го елементів списку (індекси 1 та 4)
temp = results[1]
results[1] = results[4]
results[4] = temp

print("\nСписок після обміну 2-го та 5-го елементів:")
print(results)

